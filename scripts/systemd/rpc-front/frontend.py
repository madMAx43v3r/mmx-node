"""RPC edge configuration, restricted ACME routing, and local TLS activation."""

import argparse
import contextlib
import fcntl
import hashlib
import http.server
import ipaddress
import json
import os
from pathlib import Path
import re
import socket
import ssl
import subprocess
import sys
import tempfile
import time
import urllib.error
import urllib.request

CONFIG = Path("/etc/mmx-rpc-front/config.json")
STATE = Path("/var/lib/mmx-rpc-front")
MAP = STATE / "acme.map"
SOCKET = "/run/haproxy/admin.sock"
TOKEN = re.compile(r"[A-Za-z0-9_-]{16,128}\Z")
PREFIX = "/.well-known/acme-challenge/"
LEASE_SECONDS = 1800


def run(*args, **kwargs):
    return subprocess.run(args, check=True, capture_output=True, **kwargs).stdout


def atomic(path, data, mode=0o600):
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, name = tempfile.mkstemp(prefix="." + path.name, dir=path.parent)
    try:
        with os.fdopen(fd, "wb") as output:
            os.fchmod(output.fileno(), mode)
            output.write(data.encode() if isinstance(data, str) else data)
            output.flush()
            os.fsync(output.fileno())
        os.replace(name, path)
    finally:
        Path(name).unlink(missing_ok=True)


def validate_config(config):
    if not re.fullmatch(r"[a-z0-9]+(?:[.-][a-z0-9]+)+", config["domain"]):
        raise ValueError("invalid domain")
    ids, addresses = set(), set()
    for node in config["nodes"]:
        if not re.fullmatch(r"[a-z][a-z0-9_-]{0,31}", node["id"]):
            raise ValueError("invalid node ID")
        ipaddress.ip_address(node["address"])
        if node["id"] in ids or node["address"] in addresses:
            raise ValueError("duplicate node")
        ids.add(node["id"])
        addresses.add(node["address"])
    if config["node_id"] not in ids:
        raise ValueError("local node missing from inventory")
    for key in ("total_connections", "visitor_connections", "prefix48_connections",
                "visitor_requests_10s", "prefix48_requests_10s", "idle_seconds"):
        value = config["limits"][key]
        if type(value) is not int or not 1 <= value <= 1000000:
            raise ValueError("invalid limit: " + key)
    return config


def load_config():
    return validate_config(json.loads(CONFIG.read_text()))


def endpoint(address, port):
    return f"[{address}]:{port}" if ":" in address else f"{address}:{port}"


def render_haproxy(config, map_path=MAP, http_port=80, https_port=443, plain_port=8080,
                   tls_address="127.0.0.1:18443", plain_address="127.0.0.1:18080",
                   request_port=9080, rpc_address="127.0.0.1:8081",
                   acme_address="127.0.0.1:8888", socket_path=SOCKET, ipv6=True):
    validate_config(config)
    limits, domain = config["limits"], config["domain"]
    total, idle = limits["total_connections"], limits["idle_seconds"]
    ip_hosts = []
    for node in config["nodes"]:
        address = node["address"]
        host = f"[{address}]" if ":" in address else address
        ip_hosts += [host, f"{host}:{http_port}", f"{host}:{plain_port}"]
    lines = ["# Generated by mmx-rpc-front; edit the inventory, not this file.",
             "global", "    user haproxy", "    group haproxy",
             # A TLS client also occupies a loopback HTTP connection after Caddy.
             f"    maxconn {2 * total}", f"    stats socket {socket_path} mode 600 level admin", "",
             "defaults", "    mode http", "    no log",
             "    timeout connect 5s", f"    timeout client {idle}s", f"    timeout server {idle}s",
             f"    timeout tunnel {idle}s", "    timeout http-request 5s",
             f"    timeout http-keep-alive {idle}s", "    timeout queue 5s", "",
             "backend visitors", "    stick-table type ipv6 size 100k expire 1m store conn_cur", "",
             "backend prefixes48", "    stick-table type ipv6 size 100k expire 1m store conn_cur", "",
             "backend node_total", "    stick-table type integer size 1 store conn_cur", "",
             "backend visitor_rates", "    stick-table type ipv6 size 100k expire 1m store http_req_rate(10s)", "",
             "backend prefix48_rates", "    stick-table type ipv6 size 100k expire 1m store http_req_rate(10s)", ""]
    for secure in (False, True):
        lines += ["frontend rpc_tls" if secure else "frontend rpc_plain"]
        if secure:
            lines += ["    mode tcp"]
        for port in ([https_port] if secure else [http_port, plain_port]):
            lines += [f"    bind 0.0.0.0:{port}"]
            if ipv6:
                lines += [f"    bind [::]:{port} v6only"]
        lines += [f"    maxconn {2 * total}",
                  "    tcp-request connection track-sc0 src,ipmask(32,64) table visitors",
                  "    tcp-request connection track-sc1 src,ipmask(32,48) table prefixes48 unless { src -m ip 0.0.0.0/0 }",
                  "    tcp-request connection track-sc2 int(0) table node_total",
                  f"    tcp-request connection reject if {{ sc_conn_cur(0) gt {limits['visitor_connections']} }}",
                  f"    tcp-request connection reject if {{ sc_conn_cur(1) gt {limits['prefix48_connections']} }}",
                  f"    tcp-request connection reject if {{ sc_conn_cur(2) gt {total} }}"]
        if secure:
            lines += ["    default_backend caddy_tls", ""]
        else:
            lines += ["    option httpclose", "    http-response set-header Connection close",
                      f"    acl rpc_host hdr(host),lower,field(1,:) -m str {domain}",
                      "    acl acme path_beg /.well-known/acme-challenge/",
                      "    http-request deny deny_status 400 if acme !rpc_host",
                      "    acl readiness path -m str /",
                      "    acl ip_host hdr(host),lower -m str " + " ".join(ip_hosts),
                      f"    http-request redirect location https://{domain}%[url] code 308 if {{ dst_port {http_port} }} !acme !ip_host",
                      "    http-request set-path /node/info if readiness ip_host",
                      f"    use_backend %[path,map_str({map_path},acme_local)] if acme",
                      "    default_backend caddy_plain", ""]
    # Only Caddy can reach this loopback listener. It overwrites the client header
    # using the PROXY v2 address, never a client-supplied X-Forwarded-For value.
    lines += ["frontend rpc_requests", f"    bind 127.0.0.1:{request_port}",
              "    option httpclose",
              "    http-request deny deny_status 400 unless { hdr_ip(X-Mmx-Client) -m found }",
              "    http-request track-sc0 hdr_ip(X-Mmx-Client),ipmask(32,64) table visitor_rates",
              "    http-request track-sc1 hdr_ip(X-Mmx-Client),ipmask(32,48) table prefix48_rates unless { hdr_ip(X-Mmx-Client) -m ip 0.0.0.0/0 }",
              f"    http-request return status 429 content-type text/plain string Too-many-requests hdr Retry-After 10 if {{ sc_http_req_rate(0) gt {limits['visitor_requests_10s']} }}",
              f"    http-request return status 429 content-type text/plain string Too-many-requests hdr Retry-After 10 if {{ sc_http_req_rate(1) gt {limits['prefix48_requests_10s']} }}",
              "    http-request set-header X-Forwarded-For %[hdr(X-Mmx-Client)]",
              "    http-request set-header X-Forwarded-Proto %[hdr(X-Mmx-Scheme)]",
              "    http-request del-header X-Mmx-Client", "    http-request del-header X-Mmx-Scheme",
              "    default_backend rpc", "",
              "backend rpc", f"    server rpc {rpc_address}", "",
              "backend caddy_tls", "    mode tcp", f"    server caddy {tls_address} send-proxy-v2", "",
              "backend caddy_plain", f"    server caddy {plain_address} send-proxy-v2", "",
              "backend acme_local", "    timeout server 5s", f"    server local {acme_address}", ""]
    for node in config["nodes"]:
        if node["id"] != config["node_id"]:
            lines += ["backend acme_" + node["id"], "    timeout server 5s",
                      f"    server owner {endpoint(node['address'], 80)}", ""]
    return "\n".join(lines)


def render_caddy(config, certificate_directory="/etc/caddy/rpc-front/current",
                 tls_port=18443, plain_port=18080, request_port=9080, admin="127.0.0.1:2019"):
    return """# Generated by mmx-rpc-front. Caddy terminates TLS behind HAProxy.
{
    admin %s
    auto_https off
    persist_config off
    default_bind 127.0.0.1
    servers {
        protocols h1 h2
        max_header_size 64KB
        listener_wrappers {
            proxy_protocol {
                timeout 5s
                allow 127.0.0.1/32
            }
            tls
        }
        timeouts {
            read_header 5s
            read_body 5s
            # Preserve the absolute deadline instead of resetting it on reads.
            read_body_idle -1s
            idle %ds
        }
    }
}
(rpc_backend) {
    reverse_proxy 127.0.0.1:%d {
        header_up X-Mmx-Client {http.request.remote.host}
        header_up X-Mmx-Scheme {http.request.scheme}
        transport http {
            keepalive off
        }
    }
}
https://%s:%d {
    tls %s/fullchain.pem %s/privkey.pem
    import rpc_backend
}
http://:%d {
    import rpc_backend
}
""" % (admin, config["limits"]["idle_seconds"], request_port, config["domain"], tls_port,
       certificate_directory, certificate_directory, plain_port)


def runtime(command):
    with socket.socket(socket.AF_UNIX) as connection:
        connection.settimeout(5)
        connection.connect(SOCKET)
        connection.sendall((command + "\n").encode())
        connection.shutdown(socket.SHUT_WR)
        response = b""
        while chunk := connection.recv(65536):
            response += chunk
        return response.decode().strip()


def checked_runtime(command):
    response = runtime(command)
    if response:
        raise RuntimeError("HAProxy map update failed: " + response)


@contextlib.contextmanager
def state_lock():
    STATE.mkdir(mode=0o755, parents=True, exist_ok=True)
    with (STATE / "lock").open("a") as lock:
        fcntl.flock(lock, fcntl.LOCK_EX)
        yield


def change_claim(config, owner, action, token=None, online=True):
    if owner not in {n["id"] for n in config["nodes"]}:
        raise ValueError("unknown peer")
    if action not in ("claim", "release", "prune"):
        raise ValueError("invalid action")
    if action != "prune" and not TOKEN.fullmatch(token or ""):
        raise ValueError("invalid token")
    with state_lock():
        path = STATE / "claims.json"
        previous = json.loads(path.read_text()) if path.exists() else {}
        now = time.time()
        claims = {k: v for k, v in previous.items() if v["expires"] > now}
        if token in claims and claims[token]["owner"] != owner:
            raise ValueError("token belongs to a different node")
        if action == "claim":
            if len(claims) >= 256 and token not in claims:
                raise ValueError("too many challenge claims")
            claims[token] = {"owner": owner, "expires": now + LEASE_SECONDS}
        elif action == "release":
            claims.pop(token, None)
        def backend(record):
            return "acme_local" if record["owner"] == config["node_id"] else "acme_" + record["owner"]
        # Persist first so a concurrent graceful reload sees the same routing.
        # All callers share the lock with TLS/config reloads.
        atomic(path, json.dumps(claims) + "\n")
        atomic(MAP, "".join(PREFIX + key + " " + backend(value) + "\n"
                           for key, value in sorted(claims.items())), 0o644)
        if online:
            # Reconcile the entire live map. A failed socket operation must not
            # leave a stale route forever after the disk lease has been pruned.
            active = {}
            for line in runtime(f"show map {MAP}").splitlines():
                fields = line.split()
                if len(fields) == 3 and fields[0].startswith("0x"):
                    active[fields[1]] = fields[2]
                elif line and not line.startswith("#"):
                    raise RuntimeError("unexpected HAProxy map response: " + line)
            desired = {PREFIX + key: backend(record) for key, record in claims.items()}
            for key in active.keys() - desired.keys():
                checked_runtime(f"del map {MAP} {key}")
            for key, value in desired.items():
                if key not in active:
                    checked_runtime(f"add map {MAP} {key} {value}")
                elif active[key] != value:
                    checked_runtime(f"set map {MAP} {key} {value}")


def peer_command(peer):
    return ["/usr/bin/ssh", "-F", "/dev/null", "-T", "-i", str(STATE / "id_ed25519"),
            "-o", "IdentitiesOnly=yes", "-o", "BatchMode=yes",
            "-o", "StrictHostKeyChecking=yes", "-o", "UserKnownHostsFile=" + str(STATE / "known_hosts"),
            "-o", "ConnectTimeout=5", "-o", "ServerAliveInterval=5", "-o", "ServerAliveCountMax=1",
            "root@" + peer["address"]]


def tell_peer(peer, action, token):
    return run(*peer_command(peer), input=json.dumps({"action": action, "token": token}).encode(), timeout=15)


def challenge_get(address, domain, token):
    request = urllib.request.Request("http://" + endpoint(address, 80) + PREFIX + token,
                                     headers={"Host": domain})
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open(request, timeout=5) as response:
        return response.read(1024).decode().strip()


def auth(config, token, validation):
    if not TOKEN.fullmatch(token) or not re.fullmatch(r"[A-Za-z0-9_.-]{16,512}", validation):
        raise ValueError("invalid challenge")
    challenge = STATE / "challenges" / token
    atomic(challenge, validation, 0o644)
    peers = [n for n in config["nodes"] if n["id"] != config["node_id"]]
    try:
        change_claim(config, config["node_id"], "claim", token)
        for peer in peers:
            error = None
            try:
                tell_peer(peer, "claim", token)
            except (subprocess.SubprocessError, OSError) as failure:
                error = failure
            try:
                body = challenge_get(peer["address"], config["domain"], token)
            except urllib.error.HTTPError:
                raise RuntimeError(peer["id"] + " is reachable but its challenge route is not ready") from error
            except (urllib.error.URLError, TimeoutError, OSError):
                # A dead peer must not become the certificate authority for healthy nodes.
                print(peer["id"] + ": public HTTP unreachable; continuing on healthy nodes", file=sys.stderr)
                continue
            if body != validation:
                raise RuntimeError(peer["id"] + " returned the wrong challenge response") from error
        if challenge_get("127.0.0.1", config["domain"], token) != validation:
            raise RuntimeError("local challenge route is not ready")
    except Exception:
        cleanup(config, token)
        raise


def cleanup(config, token):
    if not TOKEN.fullmatch(token):
        raise ValueError("invalid token")
    change_claim(config, config["node_id"], "release", token)
    (STATE / "challenges" / token).unlink(missing_ok=True)
    for peer in config["nodes"]:
        if peer["id"] != config["node_id"]:
            try:
                tell_peer(peer, "release", token)
            except (OSError, subprocess.SubprocessError):
                print(peer["id"] + ": cleanup deferred to lease expiry", file=sys.stderr)


def serve_challenges(config):
    class Handler(http.server.BaseHTTPRequestHandler):
        def do_GET(self):
            token = self.path.removeprefix(PREFIX)
            file = STATE / "challenges" / token
            if (self.headers.get("Host", "").split(":")[0].lower() != config["domain"]
                    or not self.path.startswith(PREFIX) or not TOKEN.fullmatch(token)):
                self.send_error(404)
                return
            try:
                data = file.read_bytes()
            except FileNotFoundError:
                self.send_error(404)
                return
            self.send_response(200)
            self.send_header("Content-Type", "text/plain")
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Connection", "close")
            self.end_headers()
            self.wfile.write(data)
            self.close_connection = True

        def log_message(self, *args):
            pass

    http.server.HTTPServer(("127.0.0.1", 8888), Handler).serve_forever()


def check_tls(domain, expected):
    context = ssl.create_default_context()
    for attempt in range(5):
        try:
            with socket.create_connection(("127.0.0.1", 443), timeout=5) as raw:
                with context.wrap_socket(raw, server_hostname=domain) as tls:
                    if tls.getpeercert(binary_form=True) == expected:
                        return
        except (OSError, ssl.SSLError):
            pass
        time.sleep(1)
    raise RuntimeError("Caddy did not serve the expected certificate")


def install_certificate(config, directory, reload=True):
    cert, key = Path(directory) / "fullchain.pem", Path(directory) / "privkey.pem"
    with tempfile.TemporaryDirectory() as temporary:
        leaf = Path(temporary) / "leaf.pem"
        run("openssl", "x509", "-in", str(cert), "-out", str(leaf))
        run("openssl", "verify", "-CAfile", "/etc/ssl/certs/ca-certificates.crt",
            "-untrusted", str(cert), "-purpose", "sslserver", "-verify_hostname", config["domain"], str(leaf))
        run("openssl", "x509", "-in", str(cert), "-checkend", "604800", "-noout")
        if run("openssl", "x509", "-in", str(cert), "-pubkey", "-noout") != run("openssl", "pkey", "-in", str(key), "-pubout"):
            raise ValueError("certificate/key mismatch")
        expected = run("openssl", "x509", "-in", str(cert), "-outform", "DER")
    import grp
    root = Path("/etc/caddy/rpc-front")
    version = hashlib.sha256(cert.read_bytes() + key.read_bytes()).hexdigest()
    with state_lock():
        gid = grp.getgrnam("caddy").gr_gid
        root.mkdir(mode=0o750, exist_ok=True)
        os.chown(root, 0, gid)
        directory = root / version
        directory.mkdir(mode=0o750, exist_ok=True)
        os.chown(directory, 0, gid)
        for name, source in (("fullchain.pem", cert), ("privkey.pem", key)):
            atomic(directory / name, source.read_bytes(), 0o640)
            os.chown(directory / name, 0, gid)
        current = root / "current"
        previous = os.readlink(current) if current.is_symlink() else None
        pending = root / ".current-next"
        pending.unlink(missing_ok=True)
        pending.symlink_to(version)
        os.replace(pending, current)
        try:
            if reload:
                run("caddy", "validate", "--config", "/etc/caddy/Caddyfile")
                run("caddy", "reload", "--config", "/etc/caddy/Caddyfile", "--force")
                try:
                    check_tls(config["domain"], expected)
                except RuntimeError:
                    run("caddy", "reload", "--config", "/etc/caddy/Caddyfile", "--force")
                    check_tls(config["domain"], expected)
        except Exception:
            if previous is not None:
                pending.symlink_to(previous)
                os.replace(pending, current)
                run("systemctl", "reload", "caddy")
            else:
                current.unlink(missing_ok=True)
            raise
    print(config["node_id"] + ": local certificate activated; sha256=" + hashlib.sha256(expected).hexdigest())


def certbot(config, staging=False, renew=False):
    executable = "/usr/local/sbin/mmx-rpc-front"
    command = ["certbot", "renew" if renew else "certonly", "--non-interactive",
               "--cert-name", config["domain"], "--manual", "--preferred-challenges", "http",
               "--manual-auth-hook", executable + " auth",
               "--manual-cleanup-hook", executable + " cleanup"]
    if not renew:
        command += ["--agree-tos", "--register-unsafely-without-email", "-d", config["domain"]]
    if staging:
        base = STATE / "staging"
        command += ["--test-cert", "--force-renewal", "--config-dir", str(base / "config"),
                    "--work-dir", str(base / "work"), "--logs-dir", str(base / "logs")]
    else:
        command += ["--deploy-hook", executable + " deploy"]
    # Certbot output contains no private keys; retain its diagnostics in the journal.
    subprocess.run(command, check=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("action", choices=["render", "render-caddy", "auth", "cleanup", "peer", "prune", "serve", "issue", "staging", "renew", "deploy", "bootstrap"])
    parser.add_argument("argument", nargs="?")
    args = parser.parse_args()
    config = load_config()
    if args.action == "render":
        print(render_haproxy(config))
    elif args.action == "render-caddy":
        print(render_caddy(config))
    elif args.action == "peer":
        # Invoked only by a pinned, forced-command SSH public key. No remote command allowed.
        if os.environ.get("SSH_ORIGINAL_COMMAND"):
            raise ValueError("remote commands are not permitted")
        data = sys.stdin.buffer.read(2049)
        if len(data) > 2048:
            raise ValueError("oversized peer message")
        request = json.loads(data)
        if set(request) != {"action", "token"} or request["action"] not in ("claim", "release"):
            raise ValueError("invalid peer message")
        change_claim(config, args.argument, request["action"], request["token"])
        print("ok")
    elif args.action == "auth":
        if os.environ["CERTBOT_DOMAIN"] != config["domain"]:
            raise ValueError("unexpected ACME domain")
        auth(config, os.environ["CERTBOT_TOKEN"], os.environ["CERTBOT_VALIDATION"])
    elif args.action == "cleanup":
        cleanup(config, os.environ["CERTBOT_TOKEN"])
    elif args.action == "prune":
        change_claim(config, config["node_id"], "prune", online=args.argument != "offline")
        with state_lock():
            for path in (STATE / "challenges").glob("*"):
                if time.time() - path.stat().st_mtime > LEASE_SECONDS:
                    path.unlink()
    elif args.action == "serve":
        serve_challenges(config)
    elif args.action in ("issue", "staging", "renew"):
        certbot(config, staging=args.action == "staging", renew=args.action == "renew")
    elif args.action == "deploy":
        expected = Path("/etc/letsencrypt/live") / config["domain"]
        if Path(os.environ.get("RENEWED_LINEAGE", str(expected))).resolve() != expected.resolve():
            raise ValueError("unexpected certificate lineage")
        install_certificate(config, expected)
    elif args.action == "bootstrap":
        install_certificate(config, args.argument, reload=False)


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        # Do not print key material or captured subprocess output.
        print(f"mmx-rpc-front: {error}", file=sys.stderr)
        sys.exit(1)
